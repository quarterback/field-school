// Run Red Pen Editor's surface inspection on the V3 sources and the student
// edition, and record word counts and possible repeated sentences/paragraphs.
// inspect() is a diagnostic only; editorial judgment is recorded in the change log.
import { readFileSync, readdirSync, appendFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { inspect } from 'red-pen-editor';

const here = dirname(fileURLToPath(import.meta.url));
const rows = [];
const add = (label, path) => {
  const r = inspect(readFileSync(path, 'utf8'));
  rows.push(`| ${label} | ${r.words} | ${(r.possibleRepeatedSentences || []).length} | ${(r.possibleRepeatedParagraphs || r.similarParagraphs || []).length} |`);
};
for (const f of ['master_project_dossier_v3.md', 'neighborhood_atlas_2030.md',
  'municipal_digital_governance_packet_v3.md', 'housing_authority_case_home_forward_vs_detroit.md',
  'before_the_municipal_service_build_v3.md']) add(`v3/${f}`, join(here, '..', '..', 'v3', f));
for (const f of readdirSync(join(here, '..', 'src')).filter(f => f.endsWith('.md')).sort())
  add(`src/${f}`, join(here, '..', 'src', f));
const out = '# Red Pen inspect results\n\nGenerated by `checks/inspect.mjs` (red-pen-editor 0.2.1 `inspect`).\n\n| File | Words | Possible repeated sentences | Possible repeated paragraphs |\n|---|---:|---:|---:|\n' + rows.join('\n') + '\n';
writeFileSync(join(here, 'inspect_report.md'), out);
console.log(out);
