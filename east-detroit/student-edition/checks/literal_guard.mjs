// Cross-document literal guard built on Red Pen Editor's protected-literal rule.
// For each V3 source file, list every protected literal (number, date, URL)
// that no longer appears anywhere in the student edition. Each one must be
// accounted for in EDITORIAL_CHANGE_LOG.md. Red Pen guards single-file span
// edits; this applies the same rule across a reorganized document set.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { protectedLiterals, countLiteral } from 'red-pen-editor';

const here = dirname(fileURLToPath(import.meta.url));
const v3 = join(here, '..', '..', 'v3');
const src = join(here, '..', 'src');
const SOURCES = [
  'master_project_dossier_v3.md',
  'neighborhood_atlas_2030.md',
  'municipal_digital_governance_packet_v3.md',
  'housing_authority_case_home_forward_vs_detroit.md',
  'before_the_municipal_service_build_v3.md',
];
const edition = readdirSync(src).filter(f => f.endsWith('.md'))
  .map(f => readFileSync(join(src, f), 'utf8')).join('\n')
  .replace(/\\\$/g, '$'); // pandoc escapes dollar signs

let report = '# Literal guard report\n\nGenerated by `checks/literal_guard.mjs` using red-pen-editor 0.2.1 `protectedLiterals`.\n\n';
let total = 0;
for (const f of SOURCES) {
  const text = readFileSync(join(v3, f), 'utf8');
  const lits = protectedLiterals(text);
  const lost = lits.filter(x => countLiteral(edition, x) === 0);
  total += lost.length;
  report += `## ${f}\n\n${lits.length} protected literals; ${lost.length} absent from the student edition.\n\n`;
  for (const l of lost) report += `- \`${l}\`\n`;
  report += '\n';
}
writeFileSync(join(here, 'literal_guard_report.md'), report);
console.log(report);
console.log(`TOTAL absent: ${total}`);

// Reverse check: literals in the student edition that appear in no source.
// These are additions and must each be justified in the change log.
const allSources = SOURCES.map(f => readFileSync(join(v3, f), 'utf8')).join('\n');
const added = protectedLiterals(edition).filter(x => countLiteral(allSources, x) === 0);
let rev = `## Added in the student edition (not in any V3 source)\n\n${added.length} literals.\n\n` + added.map(a => `- \`${a}\``).join('\n') + '\n';
writeFileSync(join(here, 'literal_guard_report.md'), report + rev);
console.log(rev);
